-- The signed-in user. security definer so policies can read users without looping.
CREATE OR REPLACE FUNCTION public.current_app_user_id()
RETURNS INTEGER
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT user_id FROM public.users
  WHERE supabase_uid = auth.uid()::text AND is_active
  LIMIT 1
$$;

CREATE OR REPLACE FUNCTION public.current_business_id()
RETURNS INTEGER
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT business_id FROM public.users
  WHERE supabase_uid = auth.uid()::text AND is_active
  LIMIT 1
$$;

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users
    WHERE supabase_uid = auth.uid()::text AND is_active AND role = 'admin'
  )
$$;

-- First workspace row. The new user has no users row yet, so table RLS cannot see a join code.
CREATE OR REPLACE FUNCTION public.provision_profile(
  p_name TEXT,
  p_role TEXT,
  p_business_name TEXT,
  p_join_code TEXT
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid UUID := auth.uid();
  account_email TEXT := lower(coalesce(auth.jwt()->>'email', ''));
  existing public.users%ROWTYPE;
  biz public.businesses%ROWTYPE;
  new_user public.users%ROWTYPE;
  code TEXT;
  attempt INTEGER := 0;
  alphabet TEXT := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'Login required.';
  END IF;
  IF account_email = '' THEN
    RAISE EXCEPTION 'Account email is missing.';
  END IF;
  IF p_role NOT IN ('admin', 'staff') THEN
    RAISE EXCEPTION 'Role must be admin or staff.';
  END IF;
  IF length(trim(coalesce(p_name, ''))) < 2 THEN
    RAISE EXCEPTION 'Full name is required.';
  END IF;

  SELECT * INTO existing FROM public.users
  WHERE users.supabase_uid = uid::text OR lower(users.email) = account_email
  LIMIT 1;
  IF FOUND THEN
    IF existing.supabase_uid IS NULL THEN
      UPDATE public.users SET supabase_uid = uid::text WHERE user_id = existing.user_id;
      existing.supabase_uid := uid::text;
    END IF;
    SELECT * INTO biz FROM public.businesses WHERE business_id = existing.business_id;
    RETURN jsonb_build_object('user', to_jsonb(existing), 'business', to_jsonb(biz));
  END IF;

  IF p_role = 'admin' THEN
    IF length(trim(coalesce(p_business_name, ''))) < 2 THEN
      RAISE EXCEPTION 'Business name is required.';
    END IF;
    LOOP
      attempt := attempt + 1;
      code := '';
      FOR i IN 1..6 LOOP
        code := code || substr(alphabet, 1 + floor(random() * length(alphabet))::INTEGER, 1);
      END LOOP;
      EXIT WHEN NOT EXISTS (SELECT 1 FROM public.businesses WHERE join_code = code);
      IF attempt > 20 THEN
        RAISE EXCEPTION 'Could not create a workspace code. Try again.';
      END IF;
    END LOOP;
    INSERT INTO public.businesses (
      business_name, business_type, currency, join_code, setup_complete, restock_budget, created_by_uid
    ) VALUES (
      trim(p_business_name), 'Unspecified', 'INR', code, FALSE, 0, uid
    ) RETURNING * INTO biz;
    INSERT INTO public.users (
      name, email, password_hash, supabase_uid, role, business_id, is_active
    ) VALUES (
      trim(p_name), account_email, 'supabase-managed', uid::text, 'admin', biz.business_id, TRUE
    ) RETURNING * INTO new_user;
    UPDATE public.businesses SET owner_id = new_user.user_id WHERE business_id = biz.business_id;
    biz.owner_id := new_user.user_id;
  ELSE
    code := upper(trim(coalesce(p_join_code, '')));
    IF code = '' THEN
      RAISE EXCEPTION 'A workspace code from the owner is required for a staff account.';
    END IF;
    SELECT * INTO biz FROM public.businesses WHERE join_code = code;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'That workspace code was not found.';
    END IF;
    INSERT INTO public.users (
      name, email, password_hash, supabase_uid, role, business_id, is_active
    ) VALUES (
      trim(p_name), account_email, 'supabase-managed', uid::text, 'staff', biz.business_id, TRUE
    ) RETURNING * INTO new_user;
  END IF;
  RETURN jsonb_build_object('user', to_jsonb(new_user), 'business', to_jsonb(biz));
EXCEPTION
  WHEN unique_violation THEN
    RAISE EXCEPTION 'An account with this email already exists.';
END;
$$;

-- Stock and its ledger row change together. Staff cannot update products directly.
CREATE OR REPLACE FUNCTION public.apply_stock_change(
  p_product_id INTEGER,
  p_transaction_type TEXT,
  p_quantity NUMERIC,
  p_unit_price NUMERIC,
  p_reason TEXT,
  p_notes TEXT,
  p_transaction_date TIMESTAMPTZ,
  p_reference_type TEXT,
  p_reference_id INTEGER
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  prod public.products%ROWTYPE;
  actor_id INTEGER;
  amount NUMERIC;
  delta NUMERIC;
  stored NUMERIC;
  new_stock NUMERIC;
  moment TIMESTAMPTZ;
  created public.transactions%ROWTYPE;
BEGIN
  SELECT user_id INTO actor_id FROM public.users
  WHERE supabase_uid = auth.uid()::text AND is_active
  LIMIT 1;
  IF actor_id IS NULL THEN
    RAISE EXCEPTION 'Login required.';
  END IF;
  SELECT * INTO prod FROM public.products WHERE product_id = p_product_id FOR UPDATE;
  IF NOT FOUND OR prod.business_id IS DISTINCT FROM public.current_business_id() THEN
    RAISE EXCEPTION 'Product not found.';
  END IF;
  IF p_transaction_type NOT IN ('sale', 'consumption', 'wastage', 'adjustment', 'receipt', 'opening') THEN
    RAISE EXCEPTION 'Unknown transaction type.';
  END IF;
  amount := p_quantity;
  IF amount = 0 THEN
    RAISE EXCEPTION 'Quantity must not be zero.';
  END IF;
  IF p_transaction_type IN ('sale', 'consumption', 'wastage', 'receipt', 'opening') THEN
    IF amount < 0 THEN
      RAISE EXCEPTION 'Quantity must be greater than zero.';
    END IF;
    IF p_transaction_type IN ('sale', 'consumption', 'wastage') THEN
      delta := -amount;
    ELSE
      delta := amount;
    END IF;
    stored := amount;
  ELSE
    delta := amount;
    stored := amount;
  END IF;
  IF NOT prod.is_active AND p_transaction_type <> 'opening' THEN
    RAISE EXCEPTION '% is inactive. Reactivate it before recording stock movement.', prod.name;
  END IF;
  new_stock := prod.current_stock + delta;
  IF new_stock < 0 THEN
    RAISE EXCEPTION 'Not enough stock for %. Available: % %.', prod.name, prod.current_stock, prod.unit;
  END IF;
  moment := coalesce(p_transaction_date, now());
  UPDATE public.products
    SET current_stock = new_stock, updated_at = now()
    WHERE product_id = prod.product_id;
  INSERT INTO public.transactions (
    product_id, business_id, user_id, transaction_type, quantity, unit_price,
    reason, notes, transaction_date, stock_after, reference_type, reference_id
  ) VALUES (
    prod.product_id, prod.business_id, actor_id, p_transaction_type, stored, p_unit_price,
    p_reason, p_notes, moment, new_stock, p_reference_type, p_reference_id
  ) RETURNING * INTO created;
  RETURN to_jsonb(created);
END;
$$;

CREATE OR REPLACE FUNCTION public.users_protect()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NEW.user_id IS DISTINCT FROM OLD.user_id
     OR NEW.role IS DISTINCT FROM OLD.role
     OR NEW.email IS DISTINCT FROM OLD.email
     OR NEW.business_id IS DISTINCT FROM OLD.business_id
     OR NEW.password_hash IS DISTINCT FROM OLD.password_hash THEN
    RAISE EXCEPTION 'That account field cannot be changed.';
  END IF;
  IF NEW.supabase_uid IS DISTINCT FROM OLD.supabase_uid THEN
    IF OLD.supabase_uid IS NOT NULL OR NEW.supabase_uid IS DISTINCT FROM auth.uid()::text THEN
      RAISE EXCEPTION 'That account field cannot be changed.';
    END IF;
  END IF;
  IF OLD.role = 'admin' AND NEW.is_active IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'The workspace owner account stays active.';
  END IF;
  IF NOT public.is_admin() AND NEW.is_active IS DISTINCT FROM OLD.is_active THEN
    RAISE EXCEPTION 'Only the workspace owner can change account status.';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.purchase_orders_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NOT public.is_admin() THEN
    IF NEW.business_id IS DISTINCT FROM OLD.business_id
       OR NEW.supplier_id IS DISTINCT FROM OLD.supplier_id
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.approved_by IS DISTINCT FROM OLD.approved_by
       OR NEW.total_cost IS DISTINCT FROM OLD.total_cost
       OR NEW.notes IS DISTINCT FROM OLD.notes
       OR NEW.expected_delivery IS DISTINCT FROM OLD.expected_delivery THEN
      RAISE EXCEPTION 'Only the workspace owner can change that order.';
    END IF;
    IF NEW.status NOT IN ('partially_received', 'received')
       OR OLD.status NOT IN ('approved', 'ordered', 'partially_received') THEN
      RAISE EXCEPTION 'Only the workspace owner can change that order status.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.purchase_order_items_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NOT public.is_admin() THEN
    IF NEW.order_id IS DISTINCT FROM OLD.order_id
       OR NEW.product_id IS DISTINCT FROM OLD.product_id
       OR NEW.quantity IS DISTINCT FROM OLD.quantity
       OR NEW.unit_cost IS DISTINCT FROM OLD.unit_cost THEN
      RAISE EXCEPTION 'Only the workspace owner can change that line.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

