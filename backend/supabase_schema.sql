-- StockWise tables and row level security for the Supabase SQL editor.
-- Paste this into Supabase → SQL Editor → Run.
-- The app connects with SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY only.
-- These policies decide what each signed-in user can read or change.
-- Login accounts live in Supabase Auth. Register in the app after this script.

CREATE TABLE IF NOT EXISTS businesses (
    business_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR(150) NOT NULL,
    business_type VARCHAR(80) NOT NULL DEFAULT 'Retail',
    currency VARCHAR(8) NOT NULL DEFAULT 'INR',
    owner_id INTEGER,
    created_by_uid UUID,
    restock_budget NUMERIC(12, 2) NOT NULL DEFAULT 0,
    join_code VARCHAR(12) NOT NULL UNIQUE,
    setup_complete BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_business_budget_nonneg CHECK (restock_budget >= 0)
);

CREATE INDEX IF NOT EXISTS ix_businesses_owner_id ON businesses (owner_id);
CREATE INDEX IF NOT EXISTS ix_businesses_join_code ON businesses (join_code);

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(512) NOT NULL,
    supabase_uid VARCHAR(36) UNIQUE,
    role VARCHAR(20) NOT NULL,
    business_id INTEGER REFERENCES businesses (business_id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_users_role CHECK (role IN ('admin', 'staff'))
);

CREATE INDEX IF NOT EXISTS ix_users_email ON users (email);
CREATE INDEX IF NOT EXISTS ix_users_supabase_uid ON users (supabase_uid);

CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    name VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_category_business_name UNIQUE (business_id, name)
);

CREATE INDEX IF NOT EXISTS ix_categories_business_id ON categories (business_id);

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(120),
    phone VARCHAR(40),
    email VARCHAR(255),
    address TEXT,
    delivery_days INTEGER NOT NULL DEFAULT 3,
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_suppliers_delivery_nonneg CHECK (delivery_days >= 0)
);

CREATE INDEX IF NOT EXISTS ix_suppliers_business_id ON suppliers (business_id);

CREATE TABLE IF NOT EXISTS products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    name VARCHAR(150) NOT NULL,
    category VARCHAR(80) NOT NULL,
    current_stock NUMERIC(12, 3) NOT NULL DEFAULT 0,
    minimum_stock NUMERIC(12, 3) NOT NULL DEFAULT 0,
    unit VARCHAR(20) NOT NULL DEFAULT 'unit',
    selling_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    purchase_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    preferred_supplier_id INTEGER REFERENCES suppliers (supplier_id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_products_stock_nonneg CHECK (current_stock >= 0),
    CONSTRAINT ck_products_minimum_nonneg CHECK (minimum_stock >= 0),
    CONSTRAINT ck_products_selling_nonneg CHECK (selling_price >= 0),
    CONSTRAINT ck_products_purchase_nonneg CHECK (purchase_price >= 0)
);

CREATE INDEX IF NOT EXISTS ix_products_business_id ON products (business_id);

CREATE TABLE IF NOT EXISTS product_suppliers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
    supplier_id INTEGER NOT NULL REFERENCES suppliers (supplier_id) ON DELETE CASCADE,
    purchase_price NUMERIC(12, 2) NOT NULL,
    minimum_order_quantity NUMERIC(12, 3) NOT NULL DEFAULT 0,
    CONSTRAINT uq_product_supplier UNIQUE (product_id, supplier_id),
    CONSTRAINT ck_link_price_nonneg CHECK (purchase_price >= 0),
    CONSTRAINT ck_link_moq_nonneg CHECK (minimum_order_quantity >= 0)
);

CREATE INDEX IF NOT EXISTS ix_product_suppliers_product ON product_suppliers (product_id);
CREATE INDEX IF NOT EXISTS ix_product_suppliers_supplier ON product_suppliers (supplier_id);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    user_id INTEGER NOT NULL REFERENCES users (user_id),
    transaction_type VARCHAR(20) NOT NULL,
    quantity NUMERIC(12, 3) NOT NULL,
    unit_price NUMERIC(12, 2),
    reason VARCHAR(200),
    notes VARCHAR(500),
    transaction_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    stock_after NUMERIC(12, 3) NOT NULL,
    reference_type VARCHAR(40),
    reference_id INTEGER,
    CONSTRAINT ck_transactions_quantity_nonzero CHECK (quantity <> 0),
    CONSTRAINT ck_transactions_type CHECK (
        transaction_type IN ('sale', 'consumption', 'wastage', 'adjustment', 'receipt', 'opening')
    )
);

CREATE INDEX IF NOT EXISTS ix_transactions_transaction_date ON transactions (transaction_date);
CREATE INDEX IF NOT EXISTS ix_transactions_business_date ON transactions (business_id, transaction_date);
CREATE INDEX IF NOT EXISTS ix_transactions_product_date ON transactions (product_id, transaction_date);

CREATE TABLE IF NOT EXISTS purchase_orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    supplier_id INTEGER NOT NULL REFERENCES suppliers (supplier_id),
    created_by INTEGER NOT NULL REFERENCES users (user_id),
    approved_by INTEGER REFERENCES users (user_id),
    status VARCHAR(30) NOT NULL DEFAULT 'draft',
    total_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expected_delivery DATE,
    received_at TIMESTAMPTZ,
    CONSTRAINT ck_purchase_orders_status CHECK (
        status IN ('draft', 'approved', 'ordered', 'partially_received', 'received', 'cancelled')
    ),
    CONSTRAINT ck_purchase_orders_total_nonneg CHECK (total_cost >= 0)
);

CREATE INDEX IF NOT EXISTS ix_purchase_orders_business_id ON purchase_orders (business_id);

CREATE TABLE IF NOT EXISTS purchase_order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES purchase_orders (order_id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
    quantity NUMERIC(12, 3) NOT NULL,
    received_quantity NUMERIC(12, 3) NOT NULL DEFAULT 0,
    unit_cost NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_po_item_qty_positive CHECK (quantity > 0),
    CONSTRAINT ck_po_item_received_nonneg CHECK (received_quantity >= 0),
    CONSTRAINT ck_po_item_received_within_ordered CHECK (received_quantity <= quantity),
    CONSTRAINT ck_po_item_cost_nonneg CHECK (unit_cost >= 0)
);

CREATE INDEX IF NOT EXISTS ix_po_items_order ON purchase_order_items (order_id);

CREATE TABLE IF NOT EXISTS restock_recommendations (
    recommendation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    urgency VARCHAR(20) NOT NULL,
    urgency_score NUMERIC(6, 2) NOT NULL,
    suggested_quantity NUMERIC(12, 3) NOT NULL,
    estimated_cost NUMERIC(12, 2) NOT NULL,
    days_until_stockout NUMERIC(8, 2),
    reason TEXT,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_restock_recommendations_business_id ON restock_recommendations (business_id);

CREATE TABLE IF NOT EXISTS simulation_runs (
    simulation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES businesses (business_id),
    user_id INTEGER NOT NULL REFERENCES users (user_id),
    scenario_type VARCHAR(40) NOT NULL,
    input_parameters JSON NOT NULL,
    results JSON NOT NULL,
    summary VARCHAR(400),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_simulation_runs_business_id ON simulation_runs (business_id);

CREATE TABLE IF NOT EXISTS token_blocklist (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
